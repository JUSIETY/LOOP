import {strict as assert} from 'node:assert';
import {buildSync} from 'esbuild';
import {readFileSync} from 'node:fs';
const load=async path=>import('data:text/javascript;base64,'+Buffer.from(buildSync({entryPoints:[path],bundle:true,platform:'node',format:'esm',packages:'external',write:false}).outputFiles[0].text).toString('base64'));
const {baselinePrediction,nearestPrediction,VISION_MODEL}=await load('lib/vision.ts');
const {disposalRule}=await load('lib/korea-rules.ts');
const items=[{id:'pet-bottle',name:'투명 생수병'},{id:'milk-carton',name:'살균 우유팩'},{id:'cardboard',name:'택배 상자'},{id:'dirty-paper-cup',name:'오염 종이컵'},{id:'glass-bottle',name:'유리병'}];
assert.equal(baselinePrediction([{className:'carton',probability:.9}],items).itemId,'cardboard');
assert.equal(baselinePrediction([{className:'paper cup',probability:.99}],items).itemId,null,'Cup shape cannot prove contamination');
assert.equal(baselinePrediction([{className:'water bottle',probability:.15},{className:'dog',probability:.85}],items).itemId,null);
assert.equal(baselinePrediction([{className:'water bottle',probability:.5},{className:'wine bottle',probability:.45}],items).itemId,null);
assert.equal(baselinePrediction([{className:'water bottle',probability:.99}],items).needsConfirmation,true);
assert.equal(baselinePrediction([{className:'water bottle',probability:NaN}],items).itemId,null);
const sample=(itemId,embedding,split='train')=>({itemId,embedding,model:VISION_MODEL,split});
const a=sample('pet-bottle',[1,0]),b=sample('glass-bottle',[0,1]);
assert.equal(nearestPrediction([1,0],[a],items).itemId,null,'One image must not take over recognition');
assert.equal(nearestPrediction([1,0],[a,a,a],items).itemId,null,'Single-class data is insufficient');
assert.equal(nearestPrediction([1,0],[a,a,a,b,b,b],items).itemId,'pet-bottle');
assert.equal(nearestPrediction([0,1],[...Array(100).fill(a),b,b,b],items).itemId,'glass-bottle','Class imbalance must not dominate');
assert.equal(nearestPrediction([1,0],[a,a,a,...Array(3).fill(sample('glass-bottle',[.99,.1]))],items).itemId,null,'Ambiguous similarity must abstain');
assert.equal(nearestPrediction([1,0],[a,a,a,...Array(3).fill(sample('glass-bottle',[0,1],'test'))],items).itemId,null,'Test data cannot train');
assert.equal(disposalRule('bottle','clear-drink','national').destination,'투명 페트병');
assert.equal(disposalRule('bottle','plastic','national').destination,'플라스틱류');
assert.equal(disposalRule('bottle','unknown','national').destination,'추가 확인 필요');
assert.equal(disposalRule('vinyl','dirty','national').destination,'지역 기준 확인');
assert.equal(disposalRule('vinyl','dirty','seoul').destination,'비닐류 · 서울 안내');
assert.notEqual(disposalRule('glass','other','national').destination,'유리병');
assert.equal(disposalRule('carton','aseptic','national').local,true);
assert.equal(disposalRule('battery','battery','national').destination,'폐전지·전용 수거');
console.log('20 regression assertions passed (logic only; not image accuracy).');
const {selectionItems,photoChoices}=await load('lib/item-options.ts');
const {defaultConfig}=await load('lib/defaults.ts');
const oldItems=defaultConfig.items.filter(i=>i.id!=='aseptic-carton');
const options=selectionItems(oldItems);
assert.equal(options.length,oldItems.length+1);
assert.equal(oldItems.some(i=>i.id==='aseptic-carton'),false,'Old snapshots must not be mutated');
assert.equal(selectionItems(options),options,'Existing carton configuration is preserved');
assert.deepEqual(photoChoices(['milk-carton'],options).map(i=>i.id),['milk-carton','aseptic-carton']);
assert.deepEqual(photoChoices(['pet-bottle','pet-bottle'],options).map(i=>i.id),['pet-bottle','plastic-container']);
assert.deepEqual(photoChoices(['unknown'],options),[]);
const custom=options.map(i=>i.id==='aseptic-carton'?{...i,category:'general',reason:'행사 기준'}:i);
assert.equal(selectionItems(custom).find(i=>i.id==='aseptic-carton').reason,'행사 기준');
console.log('7 item selection assertions passed.');
